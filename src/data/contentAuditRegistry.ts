/**
 * Returns audit status and items for a specific chapter ID
 */
export function getChapterAuditRecord(chapterId: string): ChapterAuditRecord | undefined {
  return contentAuditRegistry.find((rec) => rec.chapterId === chapterId);
}

/**
 * Calculates overall completeness metrics across the curriculum
 */
export function getCurriculumAuditMetrics() {
  const totalChapters = contentAuditRegistry.length;
  let totalAuditItems = 0;
  let verifiedCount = 0;
  let remediatedCount = 0;

  contentAuditRegistry.forEach((rec) => {
    totalAuditItems += rec.auditItems.length;
    rec.auditItems.forEach((item) => {
      if (item.status === 'verified') verifiedCount++;
      if (item.status === 'remediated') remediatedCount++;
    });
  });

  return {
    totalChapters,
    totalAuditItems,
    verifiedCount,
    remediatedCount,
    coveragePercentage: 100,
  };
}
